/**
 * Merge research batches into content/characters.json.
 *
 * Inputs:
 *   content/research/draft/B*.json        researched drafts      {characters, dropped}
 *   content/research/classified/B*.json   classified from data   {characters, dropped}
 *   content/research/adjudicated/*.json   decisions on discrepancies (optional)
 *     [{id, field, action: 'keep' | 'set', value?, contested?, note?, source?}]
 *     field 'debut' sets {debutYear, debutIssue, debutDate}; field 'mcu' sets {mcu, mcuFirst}.
 * Outputs:
 *   content/characters.json, content/FACTCHECK.md
 *
 * Usage: npx tsx scripts/merge-research.ts
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Character } from '../src/content/types'
import { validateCharacters } from '../src/content/validate'
import teams from '../content/teams.json' with { type: 'json' }

type Raw = Omit<Character, 'realName' | 'mcuFirst'> & { realName: string | null; mcuFirst: string | null }
interface Decision {
  id: string
  field: string
  action: 'keep' | 'set'
  value?: unknown
  contested?: boolean
  note?: string
  source?: string
}

const R = 'content/research'

function readBatches(folder: string): Raw[] {
  const dir = join(R, folder)
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => /^B\d+\.json$/.test(f))
    .sort()
    .flatMap((f) => (JSON.parse(readFileSync(join(dir, f), 'utf8')) as { characters: Raw[] }).characters)
}

function readDecisions(): Decision[] {
  const dir = join(R, 'adjudicated')
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .flatMap((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')) as Decision[])
}

function apply(rec: Raw, d: Decision): void {
  if (d.action === 'set') {
    if (d.field === 'debut' && d.value && typeof d.value === 'object') Object.assign(rec, d.value)
    else if (d.field === 'mcu' && d.value && typeof d.value === 'object') Object.assign(rec, d.value)
    else (rec as unknown as Record<string, unknown>)[d.field] = d.value
  }
  if (d.contested) {
    rec.answerOk = false
    const note = `Contested ${d.field}: ${d.note ?? ''}`.trim()
    rec.notes = rec.notes ? `${rec.notes} ${note}` : note
  }
  if (d.source && !rec.sources.includes(d.source) && d.source.startsWith('https://')) rec.sources.push(d.source)
}

function normalize(rec: Raw): Character {
  const realName = rec.realName && rec.realName.trim() ? rec.realName.trim() : null
  const mcuFirst = rec.mcu && rec.mcuFirst && rec.mcuFirst.trim() ? rec.mcuFirst.trim() : null
  const teamsList = [...new Set(rec.teams.filter((t) => t && t !== 'none'))]
  if (rec.primaryTeam !== 'none' && !teamsList.includes(rec.primaryTeam)) teamsList.unshift(rec.primaryTeam)
  return {
    ...rec,
    aliases: [...new Set(rec.aliases.map((a) => a.trim()).filter((a) => a && a.toLowerCase() !== rec.name.toLowerCase()))].slice(0, 8),
    realName,
    teams: teamsList.slice(0, 5),
    mcu: Boolean(rec.mcu && mcuFirst),
    mcuFirst,
    answerOk: rec.answerOk && rec.difficulty <= 4,
    caseNote: rec.caseNote.trim(),
    notes: (rec.notes ?? '').trim(),
  } as Character
}

const byId = new Map<string, Raw>()
for (const rec of [...readBatches('draft'), ...readBatches('classified')]) byId.set(rec.id, structuredClone(rec))
const decisions = readDecisions()
let applied = 0
for (const d of decisions) {
  const rec = byId.get(d.id)
  if (!rec) {
    console.warn(`decision for unknown id ${d.id} (${d.field}) skipped`)
    continue
  }
  apply(rec, d)
  applied++
}

const characters = [...byId.values()].map(normalize).sort((a, b) => a.name.localeCompare(b.name))
writeFileSync('content/characters.json', JSON.stringify(characters, null, 2) + '\n')

const issues = validateCharacters(characters, teams)
for (const i of issues) console.log(`${i.level.toUpperCase()} ${i.path}: ${i.message}`)

const contested = characters.filter((c) => c.notes)
const lines = [
  '# Fact-check notes',
  '',
  'Generated by `scripts/merge-research.ts` from the research notes and adjudication decisions.',
  'Rules: `content/research/RUBRIC.md`. Characters with a contested attribute stay guessable but are kept out of the Unmasked answer pool (`answerOk: false`).',
  '',
  `Characters: ${characters.length}. Answer pool: ${characters.filter((c) => c.answerOk).length}. With notes: ${contested.length}.`,
  '',
  '| Character | Note | Answer pool |',
  '|---|---|---|',
  ...contested.map((c) => `| ${c.name} | ${c.notes.replace(/\|/g, '/').replace(/\n/g, ' ')} | ${c.answerOk ? 'yes' : 'no'} |`),
  '',
]
writeFileSync('content/FACTCHECK.md', lines.join('\n'))

const errors = issues.filter((i) => i.level === 'error').length
console.log(
  `merged ${characters.length} characters (${characters.filter((c) => c.answerOk).length} in the answer pool), ` +
    `${applied}/${decisions.length} decisions applied, ${errors} errors, ${issues.length - errors} warnings`,
)
process.exit(errors ? 1 : 0)
